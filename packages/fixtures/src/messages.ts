import { createHash } from 'node:crypto';

import {
  type Address,
  type Blockhash,
  type Instruction,
  type V1TransactionConfig,
  appendTransactionMessageInstructions,
  compileTransactionMessage,
  compressTransactionMessageUsingAddressLookupTables,
  createTransactionMessage,
  getBase58Decoder,
  getCompiledTransactionMessageEncoder,
  pipe,
  setTransactionMessageConfig,
  setTransactionMessageFeePayer,
  setTransactionMessageLifetimeUsingBlockhash,
  setTransactionMessageLifetimeUsingDurableNonce,
  type Nonce,
  type TransactionSigner,
} from '@solana/kit';

/** A fixed, made-up blockhash so the generated bytes never change. */
export const FIXED_BLOCKHASH = getBase58Decoder().decode(
  createHash('sha256').update('solana-signing-firewall/fixtures/v0/blockhash').digest(),
) as Blockhash;

const LIFETIME = { blockhash: FIXED_BLOCKHASH, lastValidBlockHeight: 0n };

export function compileLegacy(feePayer: Address, instructions: Instruction[]) {
  return compileTransactionMessage(
    pipe(
      createTransactionMessage({ version: 'legacy' }),
      (m) => setTransactionMessageFeePayer(feePayer, m),
      (m) => setTransactionMessageLifetimeUsingBlockhash(LIFETIME, m),
      (m) => appendTransactionMessageInstructions(instructions, m),
    ),
  );
}

/** A legacy message with a durable-nonce lifetime: AdvanceNonceAccount first, the nonce as lifetime. */
export function compileLegacyWithNonce(
  feePayer: Address,
  nonce: { nonceAccountAddress: Address; nonceAuthority: TransactionSigner; value: string },
  instructions: Instruction[],
) {
  return compileTransactionMessage(
    pipe(
      createTransactionMessage({ version: 'legacy' }),
      (m) => setTransactionMessageFeePayer(feePayer, m),
      (m) =>
        setTransactionMessageLifetimeUsingDurableNonce(
          {
            nonce: nonce.value as Nonce,
            nonceAccountAddress: nonce.nonceAccountAddress,
            nonceAuthorityAddress: nonce.nonceAuthority.address,
          },
          m,
        ),
      (m) => appendTransactionMessageInstructions(instructions, m),
    ),
  );
}

export function compileV0(
  feePayer: Address,
  instructions: Instruction[],
  lookupTables: Record<Address, Address[]>,
) {
  return compileTransactionMessage(
    pipe(
      createTransactionMessage({ version: 0 }),
      (m) => setTransactionMessageFeePayer(feePayer, m),
      (m) => setTransactionMessageLifetimeUsingBlockhash(LIFETIME, m),
      (m) => appendTransactionMessageInstructions(instructions, m),
      (m) => compressTransactionMessageUsingAddressLookupTables(m, lookupTables),
    ),
  );
}

export function compileV1(
  feePayer: Address,
  instructions: Instruction[],
  config: V1TransactionConfig,
) {
  return compileTransactionMessage(
    pipe(
      createTransactionMessage({ version: 1 }),
      (m) => setTransactionMessageFeePayer(feePayer, m),
      (m) => setTransactionMessageLifetimeUsingBlockhash(LIFETIME, m),
      (m) => setTransactionMessageConfig(config, m),
      (m) => appendTransactionMessageInstructions(instructions, m),
    ),
  );
}

type Compiled = Parameters<ReturnType<typeof getCompiledTransactionMessageEncoder>['encode']>[0];

/** Encodes a compiled message as given, so tests can encode deliberately broken messages. */
export function encode(compiled: Compiled): Uint8Array {
  return new Uint8Array(getCompiledTransactionMessageEncoder().encode(compiled));
}
